# Deletes old branches from DeadlyKurbo/project-spectre, keeping main and
# claude/beautiful-knuth-vz6mlc. Run it from inside a clone of the repo
# (on Windows, use Git Bash).
#
# The branches below were listed on 2026-10-25 along with the commit each one
# pointed to. A branch is only deleted if it still points at that commit, so
# anything pushed to it since then is left alone.
set -u

REMOTE=${REMOTE:-origin}
BATCH=${BATCH:-100}

url=$(git remote get-url "$REMOTE" 2>/dev/null) || {
  echo "No git remote '$REMOTE' here. Run this inside a clone of project-spectre." >&2
  exit 1
}
case "$url" in
  *project-spectre*) ;;
  *) echo "Remote '$REMOTE' is $url, not project-spectre. Stopping." >&2; exit 1 ;;
esac

echo "Deleting up to 833 branches from $url in batches of $BATCH..."

deleted=0
kept=0
args=()

push_batch() {
  [ ${#args[@]} -eq 0 ] && return
  # --porcelain prints one line per branch: "-" deleted, "!" refused.
  while IFS= read -r line; do
    case "$line" in
      -*) deleted=$((deleted + 1)) ;;
      !*)
        kept=$((kept + 1))
        name=$(printf '%s' "$line" | cut -f2)
        echo "Kept (changed since 2026-10-25, or already gone): ${name##*refs/heads/}"
        ;;
    esac
  done < <(git push --porcelain "$REMOTE" "${args[@]}")
  args=()
  echo "  ...$deleted deleted so far"
}

while read -r sha ref; do
  [ -z "$sha" ] && continue
